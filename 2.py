import heapq

# Initial and Goal State
start = (1, 2, 3,
         4, 0, 6,
         7, 5, 8)

goal = (1, 2, 3,
        4, 5, 6,
        7, 8, 0)

# Manhattan Distance Heuristic
def heuristic(state):
    distance = 0

    for i, tile in enumerate(state):
        if tile != 0:
            goal_pos = goal.index(tile)

            x1, y1 = divmod(i, 3)
            x2, y2 = divmod(goal_pos, 3)

            distance += abs(x1-x2) + abs(y1-y2)

    return distance


# Generate possible next states
def get_neighbors(state):
    neighbors = []
    zero = state.index(0)
    row, col = divmod(zero, 3)

    moves = [
        (-1, 0, "Up"),
        (1, 0, "Down"),
        (0, -1, "Left"),
        (0, 1, "Right")
    ]

    for dr, dc, name in moves:
        nr, nc = row + dr, col + dc

        if 0 <= nr < 3 and 0 <= nc < 3:
            new_pos = nr * 3 + nc

            new_state = list(state)
            new_state[zero], new_state[new_pos] = (
                new_state[new_pos], new_state[zero]
            )

            neighbors.append((tuple(new_state), name))

    return neighbors


# Display puzzle
def display(state):
    for i in range(0, 9, 3):
        print(state[i:i+3])


# A* Algorithm
def astar(start, goal):

    pq = []
    count = 0

    heapq.heappush(pq, (heuristic(start), count, 0, start))

    parent = {start: None}
    visited = set()

    print("INITIAL STATE:")
    display(start)

    while pq:
        f, _, g, current = heapq.heappop(pq)

        if current in visited:
            continue

        visited.add(current)

        h = heuristic(current)

        print("\n----------------------")
        print("CURRENT STATE:")
        display(current)

        print("g(n) =", g)
        print("h(n) =", h)
        print("f(n) =", f)

        if current == goal:
            print("\nGOAL REACHED!")
            break

        print("\nPossible Moves:")

        for neighbor, move in get_neighbors(current):

            if neighbor not in visited:

                new_g = g + 1
                new_h = heuristic(neighbor)
                new_f = new_g + new_h

                print("\nMove:", move)
                display(neighbor)

                print("g(n) =", new_g)
                print("h(n) =", new_h)
                print("f(n) =", new_f)

                if (neighbor not in parent or
                    new_g < parent.get(neighbor + (9,), float('inf'))):

                    parent[neighbor] = current
                    count += 1

                    heapq.heappush(
                        pq, (new_f, count, new_g, neighbor)
                    )

    # Print final path
    path = []
    node = goal

    while node is not None:
        path.append(node)
        node = parent[node]

    path.reverse()

    print("\n========== FINAL PATH ==========")

    for i, state in enumerate(path):
        print("\nStep", i)
        display(state)

    print("\nTotal Moves:", len(path) - 1)


# Execute
astar(start, goal)