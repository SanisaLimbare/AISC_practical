import numpy as np

# Membership function using interpolation
def membership(x, points, values):
    return np.interp(x, points, values)


# Input temperature
temperature = 30

# Fuzzification
cold = membership(
    temperature,
    [0, 0, 15, 25, 40],
    [1, 1, 0, 0, 0]
)

warm = membership(
    temperature,
    [0, 15, 25, 35, 40],
    [0, 0, 1, 0, 0]
)

hot = membership(
    temperature,
    [0, 25, 35, 40, 40],
    [0, 0, 1, 1, 1]
)

print("Temperature:", temperature, "°C")

print("\nFuzzification:")
print("Cold:", cold)
print("Warm:", warm)
print("Hot:", hot)


# Output fan speed range
fan = np.arange(0, 101, 1)

# Output membership functions
low = np.interp(fan, [0, 0, 20, 40, 100],
                [1, 1, 1, 0, 0])

medium = np.interp(fan, [0, 20, 50, 80, 100],
                   [0, 0, 1, 0, 0])

high = np.interp(fan, [0, 60, 80, 100, 100],
                 [0, 0, 1, 1, 1])


# Rule evaluation
rule1 = cold       # IF cold THEN low
rule2 = warm       # IF warm THEN medium
rule3 = hot        # IF hot THEN high

# Apply Mamdani inference (minimum)
output_low = np.minimum(rule1, low)
output_medium = np.minimum(rule2, medium)
output_high = np.minimum(rule3, high)

# Combine rules (maximum)
aggregated = np.maximum.reduce([
    output_low,
    output_medium,
    output_high
])


# Defuzzification using centroid method
if np.sum(aggregated) == 0:
    fan_speed = 0
else:
    fan_speed = np.sum(fan * aggregated) / np.sum(aggregated)


# Final result
print("\nRule Evaluation:")
print("Rule 1 - Cold -> Low:", rule1)
print("Rule 2 - Warm -> Medium:", rule2)
print("Rule 3 - Hot -> High:", rule3)

print("\nDefuzzification:")
print("Final Fan Speed:", round(fan_speed, 2), "%")

if fan_speed < 40:
    print("Fan Status: LOW")
elif fan_speed < 70:
    print("Fan Status: MEDIUM")
else:
    print("Fan Status: HIGH")