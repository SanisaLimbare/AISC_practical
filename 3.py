# Practical 3: Min-Max Algorithm

# Game Tree
tree = {
    'A': ['B', 'C'],
    'B': ['D', 'E'],
    'C': ['F', 'G'],
    'D': 3,
    'E': 5,
    'F': 2,
    'G': 9
}

# Min-Max Algorithm
def minimax(node, is_max):

    # Check leaf node
    if node not in tree or isinstance(tree[node], int):
        print("Checking Leaf:", node,
              "Value:", tree[node])
        return tree[node]

    if is_max:
        best = float('-inf')
        print("\nMAX Node:", node)

        for child in tree[node]:
            value = minimax(child, False)
            print("MAX compares:", best, "and", value)

            best = max(best, value)

        print("Final MAX value of", node, "=", best)

    else:
        best = float('inf')
        print("\nMIN Node:", node)

        for child in tree[node]:
            value = minimax(child, True)
            print("MIN compares:", best, "and", value)

            best = min(best, value)

        print("Final MIN value of", node, "=", best)

    return best


# Main Program
print("----- MIN-MAX ALGORITHM -----")

result = minimax('A', True)

print("\nOptimal Value:", result)

# Find optimal path
root = 'A'
path = [root]
current = root
is_max = True

while current in tree and isinstance(tree[current], list):

    children = tree[current]
    values = []

    for child in children:
        if isinstance(tree[child], int):
            values.append(tree[child])
        else:
            values.append(minimax(child, not is_max))

    if is_max:
        selected = children[values.index(max(values))]
    else:
        selected = children[values.index(min(values))]

    path.append(selected)
    current = selected
    is_max = not is_max

print("\nFinal Optimal Path:", " -> ".join(path))