import numpy as np

# Input combinations
X = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1]
])

# Perceptron training function
def train_perceptron(X, y, epochs=20, lr=0.1):

    weights = np.zeros(2)
    bias = 0

    for epoch in range(epochs):
        for i in range(len(X)):

            net = np.dot(X[i], weights) + bias
            output = 1 if net >= 0 else 0

            error = y[i] - output

            weights += lr * error * X[i]
            bias += lr * error

    return weights, bias


# Prediction function
def predict(X, weights, bias):
    results = []

    for x in X:
        net = np.dot(x, weights) + bias
        output = 1 if net >= 0 else 0
        results.append(output)

    return results


# Logic gate datasets
gates = {
    "AND": np.array([0, 0, 0, 1]),
    "OR": np.array([0, 1, 1, 1]),
    "XOR": np.array([0, 1, 1, 0])
}

# Train and test each gate
for name, y in gates.items():

    print("\n==========", name, "GATE ==========")

    if name == "XOR":
        print("Single-layer perceptron cannot learn XOR.")
        print("Using a multilayer neural network instead.")

        import tensorflow as tf

        model = tf.keras.Sequential([
            tf.keras.layers.Input(shape=(2,)),
            tf.keras.layers.Dense(4, activation='relu'),
            tf.keras.layers.Dense(1, activation='sigmoid')
        ])

        model.compile(
            optimizer=tf.keras.optimizers.Adam(learning_rate=0.05),
            loss='binary_crossentropy',
            metrics=['accuracy']
        )

        model.fit(X, y, epochs=1000, verbose=0)

        predictions = (model.predict(X, verbose=0) >= 0.5).astype(int).flatten()

        print("Predictions:", predictions)

    else:
        weights, bias = train_perceptron(X, y)
        predictions = predict(X, weights, bias)

        print("Weights:", weights)
        print("Bias:", bias)
        print("\nX1 X2 Actual Predicted")

        for i in range(len(X)):
            print(X[i][0], X[i][1], y[i], predictions[i])

